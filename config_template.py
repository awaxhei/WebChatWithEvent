# 梗库（yuxia_memes.txt，一行一个，玩家可以自己改）
# 这些是「她认得」的梗，不是「她要说」的梗——提示词里已经写明只在对方先抛时接。
# ============================================================
def _load_memes():
    path = os.path.join(ROOT, "yuxia_memes.txt")
    if not os.path.isfile(path):
        return []
    items = []
    try:
        with open(path, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line or line.startswith("#"):
                    continue
                items.append(line)
    except Exception:
        return []
    return items[:40]


